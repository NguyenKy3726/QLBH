USE DbQLBH;
GO

-- Chạy một lần trên database đã có dữ liệu.
-- Mở rộng khóa đơn mua/bán và các khóa ngoại chi tiết lên 11 ký tự.
BEGIN TRY
    BEGIN TRANSACTION;

    ALTER TABLE dbo.CTMH DROP CONSTRAINT FK_CTMH_DonMH;
    ALTER TABLE dbo.CTBH DROP CONSTRAINT FK_CTBH_DonBH;
    ALTER TABLE dbo.CTMH DROP CONSTRAINT PK_CTMH;
    ALTER TABLE dbo.CTBH DROP CONSTRAINT PK_CTBH;
    ALTER TABLE dbo.DonMH DROP CONSTRAINT PK_DonMH;
    ALTER TABLE dbo.DonBH DROP CONSTRAINT PK_DonBH;

    ALTER TABLE dbo.DonMH ALTER COLUMN MaDMH char(11) NOT NULL;
    ALTER TABLE dbo.CTMH ALTER COLUMN MaDMH char(11) NOT NULL;
    ALTER TABLE dbo.DonBH ALTER COLUMN MaDBH char(11) NOT NULL;
    ALTER TABLE dbo.CTBH ALTER COLUMN MaDBH char(11) NOT NULL;
    ALTER TABLE dbo.DonBH ALTER COLUMN MaNV tinyint NULL;

    ALTER TABLE dbo.DonMH ADD CONSTRAINT PK_DonMH PRIMARY KEY (MaDMH);
    ALTER TABLE dbo.DonBH ADD CONSTRAINT PK_DonBH PRIMARY KEY (MaDBH);
    ALTER TABLE dbo.CTMH ADD CONSTRAINT PK_CTMH PRIMARY KEY (MaDMH, MaSP);
    ALTER TABLE dbo.CTBH ADD CONSTRAINT PK_CTBH PRIMARY KEY (MaDBH, MaSP);

    ALTER TABLE dbo.CTMH ADD CONSTRAINT FK_CTMH_DonMH
        FOREIGN KEY (MaDMH) REFERENCES dbo.DonMH (MaDMH);
    ALTER TABLE dbo.CTBH ADD CONSTRAINT FK_CTBH_DonBH
        FOREIGN KEY (MaDBH) REFERENCES dbo.DonBH (MaDBH);

    IF OBJECT_ID(N'dbo.GioHang', N'U') IS NULL
    BEGIN
        CREATE TABLE dbo.GioHang
        (
            MaGH int IDENTITY(1,1) NOT NULL,
            MaKH smallint NOT NULL,
            NgayCapNhat datetime2 NOT NULL
                CONSTRAINT DF_GioHang_NgayCapNhat DEFAULT (SYSDATETIME()),
            CONSTRAINT PK_GioHang PRIMARY KEY (MaGH),
            CONSTRAINT UQ_GioHang_MaKH UNIQUE (MaKH),
            CONSTRAINT FK_GioHang_KhachHang FOREIGN KEY (MaKH)
                REFERENCES dbo.KhachHang (MaKH)
        );
    END;

    IF OBJECT_ID(N'dbo.CTGioHang', N'U') IS NULL
    BEGIN
        CREATE TABLE dbo.CTGioHang
        (
            MaGH int NOT NULL,
            MaSP char(9) NOT NULL,
            SoLuong smallint NOT NULL,
            CONSTRAINT PK_CTGioHang PRIMARY KEY (MaGH, MaSP),
            CONSTRAINT CK_CTGioHang_SoLuong CHECK (SoLuong BETWEEN 1 AND 255),
            CONSTRAINT FK_CTGioHang_GioHang FOREIGN KEY (MaGH)
                REFERENCES dbo.GioHang (MaGH),
            CONSTRAINT FK_CTGioHang_SanPham FOREIGN KEY (MaSP)
                REFERENCES dbo.SanPham (MaSP)
        );
    END;

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
GO
